"""
Problem schema: The canonical representation of a math task.

A Problem is the fundamental unit of work in chuk-math-gym. It contains:
- The question/prompt to present to the agent
- The gold answer and how to verify it
- Tool policy constraints
- Difficulty metadata for curriculum learning
"""

from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field
import hashlib
import json


class DomainType(str, Enum):
    """Mathematical domains supported by chuk-math-gym."""

    ARITHMETIC = "arithmetic"
    FRACTIONS = "fractions"
    LINEAR_EQUATIONS = "linear_equations"
    WORD_PROBLEMS = "word_problems"
    QUADRATIC = "quadratic"
    GEOMETRY = "geometry"
    CALCULUS = "calculus"


class DifficultyLevel(str, Enum):
    """
    Difficulty levels with consistent semantics across domains.

    Each level maps to specific parameter ranges in generators:
    - VERY_EASY: Single operation, small positive integers
    - EASY: Single operation, larger range
    - PRETTY_EASY: Negatives allowed, division enabled
    - MEDIUM: 2 operations, larger range
    - HARD: 2+ operations, decimals
    - PRETTY_HARD: 3 operations, high precision
    - VERY_HARD: 3+ operations, full numeric range
    """

    VERY_EASY = "very_easy"
    EASY = "easy"
    PRETTY_EASY = "pretty_easy"
    MEDIUM = "medium"
    HARD = "hard"
    PRETTY_HARD = "pretty_hard"
    VERY_HARD = "very_hard"


class AnswerType(str, Enum):
    """How the answer should be verified."""

    EXACT = "exact"           # Must match exactly (integers, simple fractions)
    NUMERIC = "numeric"       # Numeric with tolerance (decimals)
    EXPRESSION = "expression" # Symbolically equivalent (algebra)
    CHOICE = "choice"         # Multiple choice selection


class ToolPolicy(str, Enum):
    """Policy for tool usage on this problem."""

    ALLOWED = "allowed"       # Agent may use tools
    FORBIDDEN = "forbidden"   # Mental math only - no tools
    REQUIRED = "required"     # Agent must use specific tools


class Problem(BaseModel):
    """
    Canonical problem representation for all math domains.

    This is the fundamental unit that flows through the entire system:
    - Generated by domain-specific generators
    - Verified by domain-specific verifiers
    - Presented to agents in the Gym environment

    Example:
        problem = Problem(
            id="arith_easy_12345",
            seed=12345,
            domain=DomainType.ARITHMETIC,
            difficulty=DifficultyLevel.EASY,
            prompt="What is 3 + 5 * 2?",
            expression="3 + 5 * 2",
            gold_answer="13",
            answer_type=AnswerType.EXACT,
        )
    """

    # Identity
    id: str = Field(description="Unique problem identifier")
    seed: int = Field(description="Deterministic seed for reproducibility")

    # Classification
    domain: DomainType = Field(description="Mathematical domain")
    difficulty: DifficultyLevel = Field(description="Difficulty level")

    # Content
    prompt: str = Field(description="Natural language question to present")
    expression: Optional[str] = Field(
        default=None,
        description="Underlying mathematical expression (if applicable)"
    )

    # Answer specification
    answer_type: AnswerType = Field(
        default=AnswerType.NUMERIC,
        description="How to verify the answer"
    )
    gold_answer: str = Field(description="Canonical correct answer")
    tolerance: Optional[float] = Field(
        default=None,
        description="Numeric tolerance for approximate answers (e.g., 1e-6)"
    )

    # Tool policy
    tool_policy: ToolPolicy = Field(
        default=ToolPolicy.ALLOWED,
        description="Whether tools can be used"
    )
    allowed_tools: Optional[list[str]] = Field(
        default=None,
        description="Specific tools allowed (if tool_policy is ALLOWED)"
    )
    forbidden_tools: Optional[list[str]] = Field(
        default=None,
        description="Specific tools forbidden"
    )

    # Difficulty axes (for curriculum learning)
    depth: Optional[int] = Field(
        default=None,
        description="Expression nesting depth (e.g., ((a+b)*c) = depth 2)"
    )
    operation_count: Optional[int] = Field(
        default=None,
        description="Number of operations in the expression"
    )
    numeric_range: Optional[tuple[float, float]] = Field(
        default=None,
        description="Range of numbers used (min, max)"
    )
    has_decimals: Optional[bool] = Field(
        default=None,
        description="Whether decimals are involved"
    )
    has_negatives: Optional[bool] = Field(
        default=None,
        description="Whether negative numbers are involved"
    )

    # Metadata
    tags: list[str] = Field(
        default_factory=list,
        description="Searchable tags for filtering"
    )
    common_mistakes: list[str] = Field(
        default_factory=list,
        description="Expected error types for this problem"
    )

    @classmethod
    def generate_id(cls, domain: DomainType, difficulty: DifficultyLevel, seed: int) -> str:
        """Generate a deterministic problem ID."""
        return f"{domain.value}_{difficulty.value}_{seed}"

    @classmethod
    def generate_id_from_content(cls, domain: DomainType, expression: str) -> str:
        """Generate a content-based ID (for problems without seeds)."""
        content_hash = hashlib.md5(expression.encode()).hexdigest()[:8]
        return f"{domain.value}_{content_hash}"

    def to_prompt_dict(self) -> dict:
        """Export as a simple prompt dict for training."""
        return {
            "id": self.id,
            "prompt": self.prompt,
            "gold_answer": self.gold_answer,
        }

    def to_full_dict(self) -> dict:
        """Export full problem specification."""
        return self.model_dump(exclude_none=True)

    def __hash__(self):
        return hash(self.id)

    def __eq__(self, other):
        if isinstance(other, Problem):
            return self.id == other.id
        return False
